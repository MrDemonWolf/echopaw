// CSS is the shared source. Native dimensions map one rem to 16 points.
import { readFileSync, writeFileSync } from "node:fs";

const css = readFileSync(new URL("../tokens.css", import.meta.url), "utf8");
const target = new URL("../../apps/native/EchoPaw/Core/DesignSystem/Tokens.generated.swift", import.meta.url);
const root = css.match(/^:root\s*\{([^}]+)\}/)?.[1];
if (!root) throw new Error("Missing root token declarations");
const values = new Map(Array.from(root.matchAll(/--ep-([\w-]+):\s*([^;]+);/g), ([, key, value]) => [key, value]));
function token(key: string): string {
  const value = values.get(key);
  if (!value) throw new Error("Missing token " + key);
  const alias = value.match(/^var\(--ep-([\w-]+)\)$/);
  return alias ? token(alias[1]) : value;
}
const lines = ["// Generated by design-system/scripts/native-tokens.ts.", "import SwiftUI", "", "enum EP {"];
for (const key of ["navy-900", "navy-800", "navy-700", "blue-600", "blue-500", "blue-400", "success", "warning", "danger", "info", "stage-light", "paper", "ink"]) {
  const hex = token(key);
  if (!/^#[0-9a-f]{6}$/i.test(hex)) throw new Error("Invalid color " + key);
  const [red, green, blue] = hex.slice(1).match(/../g)!.map(channel => parseInt(channel, 16));
  const name = key.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
  lines.push(`    static let ${name} = Color(red: ${red}/255.0, green: ${green}/255.0, blue: ${blue}/255.0)`);
}
for (const [key, name] of [["body-family", "bodyFamily"], ["heading-family", "headingFamily"]]) {
  const family = JSON.parse(token(key));
  if (typeof family !== "string" || !/^[A-Za-z ]+$/.test(family)) throw new Error("Invalid font family " + key);
  lines.push(`    static let ${name} = ${JSON.stringify(family)}`);
}
for (const [key, value] of values) {
  if (!value.endsWith("rem")) continue;
  const name = key.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
  lines.push(`    static let ${name}: CGFloat = ${parseFloat(value) * 16}`);
}
lines.push("}", "");
const contents = lines.join("\n");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== contents) throw new Error("Regenerate native tokens with bun design-system/scripts/native-tokens.ts");
} else {
  writeFileSync(target, contents);
}
